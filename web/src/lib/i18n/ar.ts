// The Arabic texts, in Modern Standard Arabic, in the shape of the English
// catalog (en.ts). Arabic tells a man from a woman in the imperative and in the
// present tense of “you”, so the texts ask without them: buttons are verbal nouns
// (“حفظ”), requests take “يُرجى” with one (“يُرجى المحاولة لاحقًا”), and what
// happened is said in the passive (“تم الحذف”). A feed is a “خلاصة”, an item a
// “مقالة”. Values that may run left to right, such as titles, names and
// addresses, are isolated, so that they do not pull the sentence around them.

import type { Messages } from './en.ts';
import { formatNumber as n, plural } from './intl.ts';

/** A value isolated from the text around it (FIRST STRONG ISOLATE … POP DIRECTIONAL ISOLATE). */
const iso = (text: string) => `\u2068${text}\u2069`;

/** A noun for one, for two, for 3 to 10, for 11 to 99, and for 100 and more (if it differs). */
type Forms = [one: string, two: string, few: string, many: string, other?: string];

/**
 * A count with its noun. One and two are said with the noun alone (“مقالة واحدة”,
 * “مقالتان”), 3 to 10 take the plural, 11 and more the singular (“11 حسابًا”).
 */
const counted = (count: number, [one, two, few, many, other = many]: Forms) =>
	plural(count, {
		one,
		two,
		few: `${n(count)} ${few}`,
		many: `${n(count)} ${many}`,
		other: `${n(count)} ${other}`
	});

