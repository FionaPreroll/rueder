/** The form for `count`: one (1, 21 …), few (2–4, 22–24 …), many (0, 5–20, 25 …). */
const forms = (count: number, one: string, few: string, many: string) =>
	plural(count, { one, few, many, other: few });

const counted = (count: number, one: string, few: string, many: string) =>
	`${n(count)} ${forms(count, one, few, many)}`;

const articles = (count: number) => counted(count, 'статья', 'статьи', 'статей');

/** Minutes after “через” or “в течение”, which take the accusative and genitive alike here. */
const minutes = (count: number) => counted(count, 'минуту', 'минуты', 'минут');

