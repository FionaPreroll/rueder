//! The API's types in TypeScript, so that the frontend and the server cannot
//! drift apart: what the server sends and reads as JSON, written out of the
//! Rust types themselves.
//!
//! Every type that goes over the API derives [`TS`] next to `Serialize` or
//! `Deserialize`, and its module lists it in a function `types`. [`generate`]
//! asks every module and writes one file, which is committed as
//! `web/src/lib/api/types.ts`. The test `tests/api_types.rs` fails when that
//! file is not what the types say today, and rewrites it when it is run with
//! `UPDATE_API_TYPES=1`.
//!
//! Types a listed type is made of come along by themselves. In TypeScript all
//! types share one room, so a type whose Rust name says little outside its
//! module is given a name of its own there with `#[ts(rename = "...")]`.

use std::any::TypeId;

use ts_rs::{Config, TS, TypeVisitor};

use crate::{api, events, filters, labels, login, profile, reports, status, subscribe, tree};

/// Where the committed file lies, seen from the crate.
pub const FILE: &str = "../web/src/lib/api/types.ts";

const HEADER: &str = "\
// The types of rueder's API: what the server sends and reads as JSON.
//
// Written out of the Rust types in server/src/. Do not edit this file: change
// the type there and run `UPDATE_API_TYPES=1 cargo test --test api_types` in
// server/. The same test fails in CI when this file is out of date.
//
// Times are strings as in RFC 3339, such as \"2026-11-11T10:08:37Z\". A field
// with `?` may be left out of a request. Errors come as plain text, not JSON.
";

/// The types of the API, gathered from the modules.
pub struct Types {
    config: Config,
    declared: Vec<Declared>,
    /// Names two different types lay claim to.
    clashes: Vec<String>,
    /// How many types the modules have listed so far.
    listed: usize,
}

struct Declared {
    rust: TypeId,
    name: String,
    text: String,
    /// Where it stands in the file: with the type the modules listed when it
    /// was found, that type itself first, then what it is made of by name.
    /// In which order `ts-rs` comes by the parts of a type differs from one
    /// compiler to the next, and the file must not.
    place: (usize, bool, String),
}

impl Types {
    fn new() -> Self {
        Self {
            // Numbers of 64 bits go out as JSON numbers. None of rueder's comes
            // near 2^53, where JavaScript stops telling them apart.
            config: Config::new().with_large_int("number"),
            declared: Vec::new(),
            clashes: Vec::new(),
            listed: 0,
        }
    }

    /// Lists a type, and with it the types it is made of.
    pub(crate) fn add<T: TS + 'static>(&mut self) -> &mut Self {
        self.listed += 1;
        self.visit::<T>();
        let rust = TypeId::of::<T>();
        // It stands first among what came with it. One that was found before,
        // as a part of another type, stays with that one.
        if let Some(found) = self.declared.iter_mut().find(|found| found.rust == rust)
            && found.place.0 == self.listed
        {
            found.place.1 = false;
        }
        self
    }
}

impl TypeVisitor for Types {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Not a type with a name, like a number or a list: only what it holds
        // can be one.
        if T::output_path().is_none() {
            T::visit_generics(self);
            return;
        }
        let rust = TypeId::of::<T>();
        if self.declared.iter().any(|known| known.rust == rust) {
            return;
        }
        let name = T::ident(&self.config);
        let text = format!(
            "{}export {}",
            T::docs().unwrap_or_default(),
            pretty(&T::decl(&self.config))
        );
        match self.declared.iter().find(|known| known.name == name) {
            // Two modules may each have their own type for the same thing,
            // like the answer that names what was made.
            Some(known) if known.text == text => return,
            Some(_) => self.clashes.push(name.clone()),
            None => {}
        }
        self.declared.push(Declared {
            rust,
            place: (self.listed, true, name.clone()),
            name,
            text,
        });
        T::visit_dependencies(self);
    }
}

/// The file with all types of the API. Fails if two types that differ want
/// the same name in TypeScript.
pub fn generate() -> anyhow::Result<String> {
    let mut types = Types::new();
    crate::types(&mut types);
    login::types(&mut types);
    profile::types(&mut types);
    api::types(&mut types);
    tree::types(&mut types);
    subscribe::types(&mut types);
    labels::types(&mut types);
    filters::types(&mut types);
    events::types(&mut types);
    status::types(&mut types);
    reports::types(&mut types);
    anyhow::ensure!(
        types.clashes.is_empty(),
        "different types with the same name in TypeScript: {}",
        types.clashes.join(", ")
    );
    types.declared.sort_by(|a, b| a.place.cmp(&b.place));
    let mut file = HEADER.to_owned();
    for declared in &types.declared {
        file.push('\n');
        file.push_str(&declared.text);
        file.push('\n');
    }
    Ok(file)
}

/// A declaration as `ts-rs` writes it, on one line, broken into lines: one for
/// every field of an object, indented by how deep it lies, and one for every
/// case of a union whose cases are objects.
///
/// It only moves spaces and line breaks. Comments keep their words and texts
/// in quotes stay as they are.
fn pretty(declaration: &str) -> String {
    let cases = cases(declaration);
    // The cases of a union stand one step in, below the name.
    let base = usize::from(cases);
    let mut out = String::with_capacity(declaration.len() * 2);
    let mut chars = declaration.chars().peekable();
    // How deep in objects, and how deep in the `<>` of a type's parameters.
    let (mut depth, mut parameters) = (0usize, 0usize);
    let line = |out: &mut String, depth: usize| {
        out.truncate(out.trim_end_matches([' ', '\t']).len());
        out.push('\n');
        out.extend(std::iter::repeat_n('\t', depth));
    };
    let skip_space = |chars: &mut std::iter::Peekable<std::str::Chars>| {
        while chars.peek().is_some_and(|c| c.is_whitespace()) {
            chars.next();
        }
    };
    if cases && let Some((name, _)) = declaration.split_once(" = ") {
        out.push_str(name);
        out.push_str(" =");
        line(&mut out, base);
        out.push_str("| ");
        chars.nth(name.len() + " = ".len() - 1);
    }
    while let Some(c) = chars.next() {
        match c {
            '"' => {
                out.push(c);
                while let Some(c) = chars.next() {
                    out.push(c);
                    match c {
                        '\\' => out.extend(chars.next()),
                        '"' => break,
                        _ => {}
                    }
                }
            }
            // The comment on a field, which ts-rs writes on lines of its own.
            '/' if chars.peek() == Some(&'*') => {
                out.push(c);
                let mut before = c;
                for c in chars.by_ref() {
                    let starts_line = out.ends_with(['\t', '\n']);
                    match c {
                        '\n' => line(&mut out, base + depth),
                        ' ' | '\t' if starts_line => {}
                        // The lines after the first begin one column in, so
                        // the stars stand below each other.
                        '*' if starts_line => out.push_str(" *"),
                        _ => out.push(c),
                    }
                    if before == '*' && c == '/' {
                        break;
                    }
                    before = c;
                }
                skip_space(&mut chars);
                line(&mut out, base + depth);
            }
            '{' => {
                out.push(c);
                skip_space(&mut chars);
                if chars.peek() == Some(&'}') {
                    chars.next();
                    out.push('}');
                } else {
                    depth += 1;
                    line(&mut out, base + depth);
                }
            }
            '}' => {
                depth = depth.saturating_sub(1);
                out.truncate(out.trim_end().len());
                // The last field ends like the others.
                if !out.ends_with(',') {
                    out.push(',');
                }
                line(&mut out, base + depth);
                out.push(c);
            }
            ',' if depth > 0 && parameters == 0 => {
                out.push(c);
                skip_space(&mut chars);
                if chars.peek() != Some(&'}') {
                    line(&mut out, base + depth);
                }
            }
            '|' if cases && depth == 0 => {
                line(&mut out, base);
                out.push(c);
            }
            '<' => {
                parameters += 1;
                out.push(c);
            }
            '>' => {
                parameters = parameters.saturating_sub(1);
                out.push(c);
            }
            _ => out.push(c),
        }
    }
    out
}

/// Whether a declaration is a union of objects, like an enum with fields.
fn cases(declaration: &str) -> bool {
    let (mut depth, mut quoted, mut union) = (0usize, false, false);
    let mut chars = declaration.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' if quoted => {
                chars.next();
            }
            '"' => quoted = !quoted,
            '{' if !quoted => depth += 1,
            '}' if !quoted => depth = depth.saturating_sub(1),
            '|' if !quoted && depth == 0 => union = true,
            _ => {}
        }
    }
    union && declaration.contains('{')
}

#[cfg(test)]
mod tests {
    use super::pretty;

    #[test]
    fn an_object_has_a_line_for_every_field() {
        assert_eq!(
            pretty(r#"type A = { a: number, b: Array<string>, c: { d: "x, {y}" | null, }, };"#),
            "type A = {\n\ta: number,\n\tb: Array<string>,\n\tc: {\n\t\td: \"x, {y}\" | null,\n\t},\n};"
        );
        assert_eq!(
            pretty("type A = { a: number };"),
            "type A = {\n\ta: number,\n};"
        );
        assert_eq!(
            pretty("type A = { a: Record<symbol, never>, b: {  } };"),
            "type A = {\n\ta: Record<symbol, never>,\n\tb: {},\n};"
        );
    }

    #[test]
    fn a_union_of_objects_has_a_line_for_every_case() {
        assert_eq!(
            pretty(r#"type A = { "kind": "all" } | { "kind": "feed", "id": number };"#),
            "type A =\n\t| {\n\t\t\"kind\": \"all\",\n\t}\n\t| {\n\t\t\"kind\": \"feed\",\n\t\t\"id\": number,\n\t};"
        );
        // A union of plain values stays on its line.
        assert_eq!(pretty(r#"type A = "a" | "b";"#), r#"type A = "a" | "b";"#);
    }

    #[test]
    fn a_comment_stands_above_its_field() {
        assert_eq!(
            pretty("type A = { /**\n * What it is, {so}.\n * More.\n */\na: number, };"),
            "type A = {\n\t/**\n\t * What it is, {so}.\n\t * More.\n\t */\n\ta: number,\n};"
        );
    }
}
